<h2>Impostazioni che cambiano il comportamento</h2>
<p>
    Dalla sezione <strong>Impostazioni</strong> attivi o disattivi alcune funzioni. Quando un'opzione è
    spenta, le scelte e le card collegate spariscono dal sistema.
</p>

<h2>Acconto</h2>
<ul>
    <li>Se attivo, il cliente può pagare una <strong>percentuale</strong> come acconto e saldare in seguito.</li>
    <li>Compare lo stato "Acconto versato" e la relativa card nel riepilogo prenotazioni.</li>
    <li>La percentuale dell'acconto si imposta nelle stesse impostazioni.</li>
</ul>

<h2>Bonifico bancario</h2>
<ul>
    <li>Se attivo, il cliente può scegliere il bonifico: riceve le coordinate e le istruzioni via email.</li>
    <li>La prenotazione resta in "Attesa bonifico" finché non confermi l'incasso.</li>
</ul>

<h2>Numero WhatsApp</h2>
<ul>
    <li>Nel gruppo <strong>Contatti</strong> imposti il numero su cui i clienti vi scrivono.</li>
    <li>Scrivilo con il prefisso internazionale, ad esempio <code>+39 345 088 4743</code>.</li>
    <li>
        Alimenta il pulsante <strong>"Scrivici su WhatsApp"</strong> nell'email dei biglietti e nella
        pagina di conferma del pagamento. Se lasci il campo vuoto, il pulsante semplicemente non compare.
    </li>
    <li>Non serve nessun abbonamento: è un normale link che apre WhatsApp con il messaggio già scritto.</li>
</ul>

<h2>Altre opzioni</h2>
<ul>
    <li>Dati bancari per il bonifico, mittente email, e parametri generali del sito.</li>
</ul>

<div class="guide-warn">
    Le modifiche alle impostazioni hanno effetto immediato sul sito e sull'admin. Verifica sempre
    l'effetto su una prenotazione di prova prima di comunicarlo ai clienti.
</div>
