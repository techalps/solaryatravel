<h2>Come vengono calcolati i ricavi</h2>
<p>
    I ricavi mostrati nella <strong>Dashboard</strong> e in <strong>Report &amp; Statistiche</strong>
    NON considerano solo i pagamenti Stripe: contano <strong>tutte le prenotazioni incassate o confermate</strong>,
    su qualsiasi canale (anche bonifico, contanti, registrazioni manuali e retroattive).
</p>

<h2>Cosa rientra nei ricavi</h2>
<p>Rientrano le prenotazioni in stato:</p>
<ul>
    <li>Acconto versato</li>
    <li>Attesa bonifico</li>
    <li>Confermata</li>
    <li>Check-in</li>
    <li>Completata</li>
</ul>
<p>Non rientrano: <strong>In attesa</strong> (non ancora pagata), <strong>Annullata</strong>, <strong>Rimborsata</strong>, <strong>No show</strong>.</p>

<h2>A quale data viene attribuito il ricavo</h2>
<p>
    Il ricavo è attribuito alla <strong>data della partenza</strong> (non alla data in cui è stata
    registrata la prenotazione). Così una prenotazione retroattiva risulta nel periodo in cui si è svolta
    l'escursione.
</p>

<div class="guide-tip">
    La card "Acconto versato" nel riepilogo prenotazioni compare solo se l'opzione acconto è attiva
    nelle Impostazioni.
</div>
