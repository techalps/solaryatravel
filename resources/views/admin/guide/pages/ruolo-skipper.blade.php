<h2>A cosa serve il ruolo Skipper</h2>
<p>
    È un account pensato per chi è a bordo. Entra nel gestionale ma vede
    <strong>soltanto la sezione Imbarco</strong>: apre la partenza del giorno, scansiona i QR dei
    biglietti e segna i passeggeri imbarcati. Nient'altro.
</p>
<p>
    Serve per dare a skipper ed equipaggio uno strumento di lavoro senza consegnare le chiavi
    di tutto il gestionale: chi ha questo ruolo <strong>non vede</strong> prenotazioni, incassi,
    pagamenti, report, tariffe, anagrafiche clienti né impostazioni.
</p>

<h2>Come creare un account Skipper</h2>
<div class="guide-step">
    <span class="guide-step-num">1</span>
    Vai su <strong>Utenti &amp; Ruoli → Nuovo utente</strong>.
</div>
<div class="guide-step">
    <span class="guide-step-num">2</span>
    Compila nome, email e password: sono le credenziali con cui lo skipper entrerà.
</div>
<div class="guide-step">
    <span class="guide-step-num">3</span>
    Scegli il ruolo <strong>Skipper (solo imbarco)</strong>
    <span class="badge rounded-pill bg-success-subtle text-success"><i class="bi bi-qr-code-scan me-1"></i>Skipper</span>
    e salva.
</div>
<p>
    Al login l'account atterra direttamente sulla pagina Imbarco: non passa dalla dashboard,
    che per lui non è accessibile.
</p>

<div class="guide-tip">
    Puoi creare <strong>un account per ogni skipper</strong> oppure uno condiviso di bordo. Un
    account per persona è preferibile: nello storico degli imbarchi resta traccia di chi ha
    effettuato le scansioni.
</div>

<h2>Cosa vede (e cosa non vede)</h2>
<ul>
    <li><strong>Vede:</strong> l'elenco delle partenze, il dettaglio di una partenza con la lista
        passeggeri, lo scanner QR e la possibilità di segnare manualmente un passeggero come
        imbarcato (utile se il QR non è leggibile).</li>
    <li><strong>Non vede:</strong> Dashboard, Prenotazioni, Programma, Assegnazione catamarani,
        Tour, Flotta, Extra, Codici sconto, Utenti, Report, Pagamenti, Commissioni agenzie,
        Impostazioni e la Guida.</li>
</ul>
<p>
    Il menu laterale mostra la sola voce <strong>Imbarco</strong>. Se un account skipper prova ad
    aprire un indirizzo di un'altra sezione — anche scrivendolo a mano nel browser — viene
    riportato all'Imbarco: il blocco è sul server, non solo un menu nascosto.
</p>

<h2>Come cambiare o revocare l'accesso</h2>
<ul>
    <li><strong>Sospendere l'accesso:</strong> da <strong>Utenti &amp; Ruoli</strong> apri l'utente e
        cambia il ruolo in <em>Cliente</em>. Perde immediatamente l'accesso al gestionale e
        l'account resta nello storico.</li>
    <li><strong>Promuovere a operatore d'ufficio:</strong> stesso percorso, ruolo
        <em>Amministratore</em>. Da quel momento vede tutto il gestionale.</li>
    <li><strong>Fine stagione:</strong> conviene riportare a <em>Cliente</em> gli skipper non più in
        servizio, così l'elenco degli account con accesso resta corto e sotto controllo.</li>
</ul>

<div class="guide-warn">
    Le credenziali di bordo girano su telefoni e tablet: usa <strong>password diverse per ogni
    skipper</strong> e cambiale a fine stagione. Un account skipper compromesso non espone
    incassi o dati di pagamento, ma consente di segnare imbarchi non avvenuti.
</div>
