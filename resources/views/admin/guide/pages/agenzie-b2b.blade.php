<h2>Cos'è il canale agenzie (B2B)</h2>
<p>
    Le <strong>agenzie partner</strong> vendono le escursioni Solarya ai loro clienti. Solarya
    incassa sempre l'intero importo dal cliente e riconosce all'agenzia una <strong>provvigione</strong>
    (una percentuale). Le agenzie operano da un portale dedicato su
    <strong>b2b.solaryatravel.com</strong>, separato dal sito e dall'admin.
</p>

<h2>Creare un'agenzia</h2>
<p>
    Da <strong>Utenti &amp; Ruoli → Nuovo utente</strong>, scegli il ruolo <strong>Agenzia (B2B)</strong>:
    compaiono i campi <strong>Ragione sociale</strong> e <strong>Provvigione %</strong>. L'agenzia accederà
    al portale con email e password che imposti qui.
</p>
<div class="guide-tip">
    La <strong>provvigione %</strong> vale per le prenotazioni <em>future</em>. Le commissioni già
    maturate non cambiano se in seguito modifichi la percentuale (viene "fotografata" su ogni prenotazione).
</div>

<h2>Come l'agenzia genera prenotazioni</h2>
<ul>
    <li><strong>Dal portale</strong> — l'agenzia compila la prenotazione per il cliente, esattamente
        come sul sito. Il cliente riceve via email gli estremi di pagamento (link carta o bonifico) e paga lui.</li>
    <li><strong>Con link / QR referral</strong> — l'agenzia condivide il proprio link (o il volantino
        con QR): il cliente prenota da solo sul sito e la vendita risulta comunque dell'agenzia.</li>
    <li><strong>Con il widget sul proprio sito</strong> — l'agenzia incorpora il modulo di prenotazione
        Solarya direttamente nelle proprie pagine: il cliente prenota e paga senza uscire dal sito
        dell'agenzia, e la vendita risulta dell'agenzia.</li>
</ul>
<p>In tutti i casi <strong>il prezzo è quello standard</strong>: l'agenzia non può modificarlo.</p>

<h2>Il widget per il sito dell'agenzia</h2>
<p>
    Dal portale, in <strong>Widget per il sito</strong>, l'agenzia trova un piccolo codice da incollare
    nel proprio sito. Da quel momento i suoi visitatori prenotano le crociere senza lasciare le sue pagine;
    il pagamento (carta o bonifico) lo fa il cliente, Solarya incassa e l'agenzia matura la commissione,
    esattamente come con il link referral.
</p>
<div class="guide-tip">
    Il widget usa lo <strong>stesso codice agenzia</strong> del link/QR (il <em>referral_token</em>): è solo
    un altro modo di proporre la prenotazione. Non serve fare nulla lato admin per attivarlo — l'agenzia è
    autonoma. Facoltativamente l'agenzia può limitare i <strong>domini</strong> su cui il widget funziona.
</div>

<h2>Gli admin nel portale agenzie</h2>
<p>
    Super Admin e System Admin possono entrare nel portale col proprio account e
    <strong>operare per conto di un'agenzia</strong> (la scelgono e possono cambiarla in qualsiasi
    momento). Le prenotazioni così create risultano dell'agenzia scelta.
</p>

<h2>Commissioni: dove le vedi e come le paghi</h2>
<p>In <strong>Analisi → Commissioni Agenzie</strong> trovi, mese per mese:</p>
<ul>
    <li><strong>Generato</strong> — totale incassato dai clienti dell'agenzia (IVA inclusa).</li>
    <li><strong>Commissione maturata</strong> — la provvigione dovuta all'agenzia.</li>
    <li><strong>Già pagate</strong> / <strong>Da liquidare</strong> — quanto le hai già versato e quanto resta.</li>
</ul>
<p>
    Aprendo il <strong>dettaglio di un'agenzia</strong> vedi le singole prenotazioni: puoi
    <strong>segnare pagata</strong> una commissione, oppure selezionarne più di una e
    <strong>liquidarle in blocco</strong>. La marcatura "pagata" è manuale: la fai quando hai
    effettivamente versato la provvigione.
</p>

<h2>Annullamenti e storno della commissione</h2>
<div class="guide-tip">
    Se una prenotazione d'agenzia viene <strong>annullata o rimborsata</strong>, la sua commissione
    viene <strong>azzerata e marcata "Stornata"</strong> automaticamente. L'eventuale penale trattenuta
    è ricavo di Solarya e non genera provvigione.
</div>
<p>
    L'agenzia non può annullare o modificare da sola: può solo <strong>richiederlo</strong>. La richiesta
    ti arriva via email e compare nel <strong>dettaglio della prenotazione</strong> (badge B2B), dove la
    valuti e la confermi o rifiuti applicando l'eventuale penale.
</p>

<h2>Riconoscere le prenotazioni B2B</h2>
<p>
    Nelle prenotazioni admin, quelle di un'agenzia hanno il badge <strong>B2B</strong> accanto al numero;
    nel dettaglio trovi un riquadro con l'agenzia, il canale (portale, referral o widget) e la commissione.
</p>
