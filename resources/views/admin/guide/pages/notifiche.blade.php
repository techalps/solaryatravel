<h2>A cosa serve il centro notifiche</h2>
<p>
    La <strong>campanella in alto a destra</strong> ti dice cosa sta succedendo senza che tu debba
    controllare l'elenco prenotazioni: nuove prenotazioni, incassi, scadenze, annullamenti.
    Il numero rosso conta le notifiche <strong>non lette</strong>.
</p>

<h2>Letto ed eliminato valgono solo per te</h2>
<div class="guide-tip">
    Ogni operatore ha il <strong>suo</strong> stato. Se leggi o elimini una notifica, i colleghi
    continuano a vederla come nuova: non stai nascondendo niente a nessuno.
</div>

<h2>Quando compare l'avviso a schermo</h2>
<p>
    Per gli eventi importanti compare un <strong>riquadro in alto a destra</strong> (si chiude da
    sé dopo qualche secondo, o con la X). Vale per: nuova prenotazione, pagamento ricevuto,
    bonifico da verificare, annullamento, rimborso e richieste delle agenzie.
</p>
<ul>
    <li>
        <strong>Le prenotazioni che crei tu dall'admin non ti avvisano.</strong> L'avviso serve a
        segnalarti quello che arriva da fuori: sarebbe inutile dirti che è arrivata una
        prenotazione che hai appena inserito. Gli altri operatori invece la vedono.
    </li>
    <li>
        Scadenze e documenti mancanti <strong>non fanno comparire il riquadro</strong>: restano
        nell'elenco e nel contatore. Non sono novità improvvise, sono cose da smaltire.
    </li>
</ul>

<h2>Quanto è "in tempo reale"</h2>
<p>
    L'aggiornamento avviene <strong>ogni 30 secondi</strong>, senza ricaricare la pagina: appena
    arriva una prenotazione, entro mezzo minuto vedi il numero cambiare e comparire l'avviso.
</p>
<div class="guide-warn">
    Non è un aggiornamento istantaneo al millisecondo: l'hosting del sito non permette una
    connessione sempre aperta col browser. Nella pratica la differenza non si nota, ma se ti serve
    l'istantaneo si può aggiungere un servizio esterno dedicato.
</div>

<h2>Le scadenze dipendono da un'operazione automatica</h2>
<p>
    Le segnalazioni di <strong>prenotazione in scadenza</strong>, <strong>saldo scaduto</strong> e
    <strong>documenti mancanti</strong> vengono generate da un controllo che gira
    <strong>ogni ora</strong> sul server, insieme ai promemoria email. Non compaiono nell'istante
    esatto in cui la condizione si verifica, ma entro l'ora.
</p>
<p>
    Ogni segnalazione è creata <strong>una volta sola</strong> per prenotazione: non ti ritrovi la
    stessa cosa ripetuta a ogni controllo.
</p>

<h2>Cosa fare con una notifica</h2>
<div class="guide-step"><span class="guide-step-num">1</span><div><strong>Aprila.</strong> Dalla campanella o da <em>Notifiche</em> nel menu; se è legata a una prenotazione, il pulsante ti porta direttamente alla sua scheda (e la segna letta).</div></div>
<div class="guide-step"><span class="guide-step-num">2</span><div><strong>Segnala letta</strong> con la spunta verde, se ti basta averla vista.</div></div>
<div class="guide-step"><span class="guide-step-num">3</span><div><strong>Eliminala</strong> con il cestino quando l'hai smaltita. Sparisce dal tuo elenco, non da quello dei colleghi.</div></div>
<p class="text-muted small">
    In cima alla pagina ci sono anche <em>Segna tutte lette</em> e <em>Elimina tutte</em>, che
    valgono su tutte le notifiche che vedi tu.
</p>
