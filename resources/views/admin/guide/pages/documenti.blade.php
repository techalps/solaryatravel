<h2>Documento d'identità obbligatorio</h2>
<p>
    Per contratto <strong>ogni passeggero</strong> — intestatario compreso — deve avere un
    documento d'identità valido fino alla data del viaggio. I campi richiesti sono gli stessi
    su sito cliente, portale agenzie e admin:
</p>
<ul>
    <li><strong>Tipo</strong>: carta d'identità, passaporto o patente di guida.</li>
    <li><strong>Numero</strong> del documento.</li>
    <li><strong>Scadenza</strong>: deve essere uguale o successiva alla data del viaggio.</li>
    <li><strong>Luogo di emissione</strong>: Stato → Provincia → Comune. Se lo Stato è l'Italia
        compaiono le liste ufficiali di province e comuni; per l'estero il luogo è a testo libero.</li>
</ul>

<div class="guide-warn">
    Il controllo sulla scadenza è <strong>bloccante</strong> ovunque: un documento che scade
    prima del giorno del viaggio non permette di salvare la prenotazione.
</div>

<h2>Chi può inserire e modificare</h2>
<ul>
    <li><strong>Cliente e agenzia</strong> inseriscono i documenti al momento della prenotazione,
        ma <strong>non possono modificarli dopo</strong>: per correggere un dato devono contattare Solarya.</li>
    <li><strong>Solo l'admin</strong> può modificare il documento di un passeggero su una prenotazione
        esistente: apri la prenotazione, nella tabella <em>Partecipanti</em> usa il pulsante
        <em>Modifica</em>/<em>Inserisci</em> nella colonna Documento.</li>
</ul>

<h2>Prenotazioni senza documento</h2>
<p>
    Le prenotazioni create prima di questa funzione (o importate) possono non avere i documenti.
    Nella lista prenotazioni:
</p>
<ul>
    <li>Le prenotazioni <strong>future</strong> con documenti incompleti mostrano il badge
        <span class="badge rounded-pill bg-warning-subtle text-warning"><i class="bi bi-person-vcard me-1"></i>Doc. mancante</span>.</li>
    <li>In cima alla lista un avviso conta quante prenotazioni future sono incomplete, con il
        pulsante <em>Mostra solo queste</em> per filtrarle e completarle prima della partenza.</li>
</ul>

<div class="guide-tip">
    Completa i documenti mancanti prima del check-in: al momento dell'imbarco devono corrispondere
    al documento fisico esibito dal passeggero.
</div>
